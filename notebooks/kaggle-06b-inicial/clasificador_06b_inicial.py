        'def _cronometro(mods):\n'
        '    """Callback que mide el tiempo entre fines de paso consecutivos (con sincronización de CUDA)."""\n'
        '    torch = mods.torch\n'
        '\n'
        '    class Cronometro(mods.TrainerCallback):\n'
        '        def __init__(self):\n'
        '            self.tiempos: list[float] = []\n'
        '            self._t = None\n'
        '\n'
        '        def on_train_begin(self, args, state, control, **kwargs):\n'
        '            torch.cuda.synchronize()\n'
        '            self._t = time.perf_counter()\n'
        '\n'
        '        def on_step_end(self, args, state, control, **kwargs):\n'
        '            torch.cuda.synchronize()\n'
        '            t = time.perf_counter()\n'
        '            self.tiempos.append(t - self._t)\n'
        '            self._t = t\n'
        '\n'
        '    return Cronometro()\n'
        '\n'
        '\n'
        'class ColadorMedido:\n'
        '    """Colador que registra ejemplos y fichas de cada lote, en orden (dataloader sin workers)."""\n'
        '\n'
        '    def __init__(self, torch, pad_id: int):\n'
        '        self.torch = torch\n'
        '        self.pad_id = pad_id\n'
        '        self.lotes: list[dict] = []\n'
        '\n'
        '    def __call__(self, ejemplos):\n'
        '        lote, medidas = colar(ejemplos, self.pad_id)\n'
        '        self.lotes.append(medidas)\n'
        '        return {k: self.torch.tensor(v, dtype=self.torch.long) for k, v in lote.items()}\n'
        '\n'
        '\n'
        'def entrenar(mods, model, tok, ejemplos: Sequence[Mapping], *, lote: int, etiqueta: str, max_pasos: int | None = None) -> dict:\n'
        '    """Entrena con Trainer y el colador propio; devuelve tiempos, fichas, pérdida y VRAM pico."""\n'
        '    torch = mods.torch\n'
        '    colador = ColadorMedido(torch, tok.pad_token_id)\n'
        '    cronometro = _cronometro(mods)\n'
        '    bf16 = bf16_nativo(torch)\n'
        '    args = mods.TrainingArguments(\n'
        '        output_dir=str(DIR_TRABAJO / f"trainer_{etiqueta}"),\n'
        '        per_device_train_batch_size=lote,\n'
        '        max_steps=max_pasos if max_pasos else -1,\n'
        '        fp16=not bf16,\n'
        '        bf16=bf16,\n'
        '        save_strategy="no",\n'
        '        report_to="none",\n'
        '        dataloader_num_workers=0,\n'
        '        remove_unused_columns=False,\n'
        '        disable_tqdm=True,\n'
        '        **ENTRENAMIENTO,\n'
        '    )\n'
        '    ds = mods.datasets.Dataset.from_list([{"input_ids": e["input_ids"], "labels": e["labels"]} for e in ejemplos])\n'
        '    mods.transformers.set_seed(SEMILLA)\n'
        '    gc.collect()\n'
        '    torch.cuda.empty_cache()\n'
        '    torch.cuda.reset_peak_memory_stats()\n'
        '    t = time.perf_counter()\n'
        '    trainer = mods.Trainer(model=model, args=args, train_dataset=ds, data_collator=colador, callbacks=[cronometro])\n'
        '    trainer.train()\n'
        '    torch.cuda.synchronize()\n'
        '    segundos = time.perf_counter() - t\n'
        '    pasos = len(cronometro.tiempos)\n'
        '    lotes = colador.lotes[:pasos]\n'
        '    res = {\n'
        '        "lote": lote,\n'
        '        "max_pasos": max_pasos,\n'
        '        "fp16": not bf16,\n'
        '        "segundos_train_total": round(segundos, 2),\n'
        '        "lotes_registrados_por_el_colador": len(colador.lotes),\n'
        '        "vram_pico_mib": {\n'
        '            "asignada": round(torch.cuda.max_memory_allocated() / 2**20, 1),\n'
        '            "reservada": round(torch.cuda.max_memory_reserved() / 2**20, 1),\n'
        '        },\n'
        '    }\n'
        '    if len(lotes) == pasos:\n'
        '        res["estadisticas"] = estadisticas_pasos(\n'
        '            cronometro.tiempos, [x["ejemplos"] for x in lotes], [x["fichas_reales"] for x in lotes]\n'
        '        )\n'
        '        res["pasos"] = [\n'
        '            {"paso": i + 1, "s": round(s, 5), **x} for i, (s, x) in enumerate(zip(cronometro.tiempos, lotes))\n'
        '        ]\n'
        '    else:\n'
        '        res["estadisticas"] = {"error": "El colador registró menos lotes que pasos; no se emparejan."}\n'
        '        res["pasos_s"] = [round(s, 5) for s in cronometro.tiempos]\n'
        '    res["perdida"] = [\n'
        '        {"paso": h.get("step"), "loss": h.get("loss"), "grad_norm": h.get("grad_norm"), "learning_rate": h.get("learning_rate")}\n'
        '        for h in trainer.state.log_history\n'
        '        if "loss" in h\n'
        '    ]\n'
        '    del trainer\n'
        '    return res\n'
        '\n'
        '\n'
        'def _es_sin_memoria(e: BaseException) -> bool:\n'
        '    return "out of memory" in str(e).lower()\n'
        '\n'
        '\n'
        'def medir_lote(mods, model, tok, ejemplos, *, lote: int, etiqueta: str) -> dict:\n'
        '    """Medición desechable de un tamaño de lote; si se queda sin memoria, lo registra y sigue."""\n'
        '    try:\n'
        '        return entrenar(mods, model, tok, ejemplos, lote=lote, etiqueta=etiqueta, max_pasos=PASOS_LOTE)\n'
        '    except RuntimeError as e:\n'
        '        if not _es_sin_memoria(e):\n'
        '            raise\n'
        '        return {"lote": lote, "sin_memoria": True, "error": f"{type(e).__name__}: {str(e)[:300]}"}\n'
        '    finally:\n'
        '        gc.collect()\n'
        '        mods.torch.cuda.empty_cache()\n'
        '\n'
        '\n'
        'def inferir(reg: Registro, mods, model, tok, val: Sequence[Mapping], ids_fin: Sequence[int]) -> None:\n'
        '    """Greedy, lote de 1, misma plantilla; escribe predicciones.jsonl (id y respuesta cruda)."""\n'
        '    torch = mods.torch\n'
        '    mods.FastLanguageModel.for_inference(model)\n'
        '    gen = copy.deepcopy(model.generation_config)\n'
        '    gen.do_sample = False\n'
        '    gen.num_beams = 1\n'
        '    for atributo in ("temperature", "top_p", "top_k", "min_p"):\n'
        '        if hasattr(gen, atributo):\n'
        '            setattr(gen, atributo, None)\n'
        '    gen.max_new_tokens = MAX_NEW_TOKENS\n'
        '    gen.eos_token_id = list(ids_fin)\n'
        '    gen.pad_token_id = tok.pad_token_id\n'
        '    torch.cuda.reset_peak_memory_stats()\n'
        '    pares, motivos, generadas = [], {}, []\n'
        '    respaldo = False\n'
        '    t = time.perf_counter()\n'
        '    for i, r in enumerate(val, start=1):\n'
        '        enc = tok(prompt_generacion(r["nom_estab"]), add_special_tokens=False, return_tensors="pt").to("cuda")\n'
        '        with torch.inference_mode():\n'
        '            try:\n'
        '                salida = model.generate(**enc, generation_config=gen)\n'
        '            except TypeError:\n'
        '                # Respaldo, solo una vez: si la generación no acepta None en los parámetros de\n'
        '                # muestreo, se ponen valores neutros. Con do_sample=False siguen sin usarse (greedy).\n'
        '                if respaldo or i != 1:\n'
        '                    raise\n'
        '                respaldo = True\n'
        '                gen.temperature, gen.top_p, gen.top_k = 1.0, 1.0, 50\n'
        '                salida = model.generate(**enc, generation_config=gen)\n'
        '        nuevos = salida[0, enc["input_ids"].shape[1]:].tolist()\n'
        '        corte, motivo = cortar_respuesta(nuevos, ids_fin)\n'
        '        pares.append((r["id"], tok.decode(corte, skip_special_tokens=False)))\n'
        '        motivos[motivo] = motivos.get(motivo, 0) + 1\n'
        '        generadas.append(len(nuevos))\n'
        '        if i % 50 == 0:\n'
        '            informar(f"inferencia: {i} de {len(val)} filas")\n'
        '    torch.cuda.synchronize()\n'
        '    segundos = time.perf_counter() - t\n'
        '    datos = serializar_predicciones(pares)\n'
        '    ruta = DIR_SALIDA / ARCHIVO_PREDICCIONES\n'
        '    ruta.write_bytes(datos)\n'
        '    reg.datos["inferencia"] = {\n'
        '        "filas": len(pares),\n'
        '        "lote": 1,\n'
        '        "segundos": round(segundos, 2),\n'
        '        "s_por_fila": round(segundos / max(len(pares), 1), 4),\n'
        '        "terminacion": motivos,\n'
        '        "fichas_generadas_max": max(generadas) if generadas else 0,\n'
        '        "respaldo_parametros_de_muestreo": respaldo,\n'
        '        "generation_config": {\n'
        '            k: getattr(gen, k, None)\n'
        '            for k in ("do_sample", "num_beams", "temperature", "top_p", "top_k", "max_new_tokens", "eos_token_id", "pad_token_id")\n'
        '        },\n'
        '        "vram_pico_mib": round(torch.cuda.max_memory_allocated() / 2**20, 1),\n'
        '        "archivo": {"nombre": ARCHIVO_PREDICCIONES, "bytes": len(datos), "sha256": sha256_bytes(datos)},\n'
        '    }\n'
