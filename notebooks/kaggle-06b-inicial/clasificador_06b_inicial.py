        'def cargar(mods, modelo: Mapping[str, str], max_seq: int) -> tuple[object, object, dict]:\n'
        '    """Como hk.cargar, con el largo máximo de la corrida: NF4 desde el repo exacto y la revisión fijada."""\n'
        '    torch = mods.torch\n'
        '    torch.cuda.reset_peak_memory_stats()\n'
        '    model, tok = mods.FastLanguageModel.from_pretrained(\n'
        '        model_name=modelo["repo"],\n'
        '        revision=modelo["revision"],\n'
        '        use_exact_model_name=True,\n'
        '        load_in_4bit=True,\n'
        '        max_seq_length=max_seq,\n'
        '        dtype=None,\n'
        '        random_state=SEMILLA,\n'
        '    )\n'
        '    qc = getattr(model.config, "quantization_config", None)\n'
        '    qd = qc if isinstance(qc, Mapping) else (qc.to_dict() if qc is not None else {})\n'
        '    if not qd.get("load_in_4bit") or qd.get("bnb_4bit_quant_type") != "nf4":\n'
        '        raise AbortoCorrida(f"{modelo[\'repo\']}: no se cargó en NF4 de 4 bits ({qd.get(\'bnb_4bit_quant_type\')}).")\n'
        '    if tok.pad_token_id is None:\n'
        '        raise AbortoCorrida(f"{modelo[\'repo\']}: el tokenizador no tiene token de relleno.")\n'
        '    info = {\n'
        '        "repo_pedido": modelo["repo"],\n'
        '        "revision_fijada": modelo["revision"],\n'
        '        "name_or_path": model.config._name_or_path,\n'
        '        "dtype": str(getattr(model, "dtype", None)),\n'
        '        "max_seq_length_pedido": max_seq,\n'
        '        "max_seq_length_del_modelo": getattr(model, "max_seq_length", None),\n'
        '        "cuantizacion": {k: qd.get(k) for k in sorted(qd) if k.startswith(("load_in", "bnb_", "quant_method"))},\n'
        '        "capas_linear4bit": sum(1 for m in model.modules() if type(m).__name__ == "Linear4bit"),\n'
        '        "vram_tras_carga_mib": round(torch.cuda.memory_allocated() / 2**20, 1),\n'
        '        "tokenizador": {\n'
        '            "eos": tok.eos_token,\n'
        '            "pad": tok.pad_token,\n'
        '            "pad_id": tok.pad_token_id,\n'
        '            "padding_side": getattr(tok, "padding_side", None),\n'
        '            "plantilla_sha256": hk.sha256_bytes(str(tok.chat_template).encode("utf-8")),\n'
        '        },\n'
        '    }\n'
        '    return model, tok, info\n'
        '\n'
        '\n'
        'def aplicar_lora(mods, model, lora: Mapping) -> tuple[object, dict]:\n'
        '    mods.transformers.set_seed(SEMILLA)\n'
        '    model = mods.FastLanguageModel.get_peft_model(model, **dict(lora))\n'
        '    entrenables = sum(p.numel() for p in model.parameters() if p.requires_grad)\n'
        '    total = sum(p.numel() for p in model.parameters())\n'
        '    return model, {"parametros_entrenables": entrenables, "parametros_totales": total}\n'
        '\n'
