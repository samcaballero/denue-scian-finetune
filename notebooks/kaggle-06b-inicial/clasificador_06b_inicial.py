        'def verificar_base_16(reg: Registro, mods, model, ruta_oficial: Path) -> bool:\n'
        '    """¿La fusión para el GGUF usará pesos idénticos a los oficiales en la revisión fijada?\n'
        '\n'
        '    Unsloth fusiona sobre la base de 16 bits que resuelve `get_model_name(_name_or_path,\n'
        '    load_in_4bit=False)`, en la revisión main del repo resuelto. Camino "exacto": resuelve al\n'
        '    repo oficial (o a nuestra carpeta local) y main es la revisión fijada. Camino "espejo":\n'
        '    resuelve a unsloth/Qwen3-0.6B; main debe ser la revisión fijada del espejo y sus tensores,\n'
        '    idénticos a los oficiales (SHA-256 por tensor, con lm_head atado a los embeddings).\n'
        '    """\n'
        '    info: dict = {"name_or_path": model.config._name_or_path}\n'
        '    reg.datos["base_16_bits"] = info\n'
        '    try:\n'
        '        from unsloth.models.loader_utils import get_model_name\n'
        '\n'
        '        resuelto = get_model_name(model.config._name_or_path, load_in_4bit=False) or model.config._name_or_path\n'
        '    except Exception as e:  # la fusión hace lo mismo: si falla, usa _name_or_path\n'
        '        info["get_model_name_error"] = f"{type(e).__name__}"\n'
        '        resuelto = model.config._name_or_path\n'
        '    info["base_resuelta_por_unsloth"] = str(resuelto)\n'
        '    api = mods.hf.HfApi()\n'
        '    if os.path.isdir(str(resuelto)):\n'
        '        info["camino"] = "exacto_local"\n'
        '        ok = Path(resuelto).resolve() == Path(ruta_oficial).resolve()\n'
        '        info["carpeta_es_la_revision_fijada"] = ok\n'
        '        return ok\n'
        '    if str(resuelto).lower() == MODELO_06B["repo"].lower():\n'
        '        info["camino"] = "exacto"\n'
        '        main = api.model_info(MODELO_06B["repo"]).sha\n'
        '        info["main_actual"] = main\n'
        '        return main == MODELO_06B["revision"]\n'
        '    if str(resuelto).lower() != BASE_16_ESPEJO["repo"].lower():\n'
        '        info["camino"] = "desconocido"\n'
        '        return False\n'
        '\n'
        '    info["camino"] = "espejo"\n'
        '    main = api.model_info(BASE_16_ESPEJO["repo"]).sha\n'
        '    info["main_actual_del_espejo"] = main\n'
        '    info["revision_fijada_del_espejo"] = BASE_16_ESPEJO["revision"]\n'
        '    if main != BASE_16_ESPEJO["revision"]:\n'
        '        info["motivo"] = "La rama main del espejo no es la revisión fijada: la fusión usaría pesos no verificados."\n'
        '        return False\n'
        '    ruta_espejo, verif = descargar_verificado(\n'
        '        mods, BASE_16_ESPEJO["repo"], BASE_16_ESPEJO["revision"], ["config.json", "*.safetensors", "*.json"]\n'
        '    )\n'
        '    info["espejo_lfs_verificado"] = verif\n'
        '    t = time.perf_counter()\n'
        '    oficial = hashes_safetensors(sorted(ruta_oficial.glob("*.safetensors")))\n'
        '    espejo = hashes_safetensors(sorted(ruta_espejo.glob("*.safetensors")))\n'
        '    comparacion = comparar_tensores(\n'
        '        oficial, espejo, _atado(ruta_oficial / "config.json"), _atado(ruta_espejo / "config.json")\n'
        '    )\n'
        '    comparacion["segundos"] = round(time.perf_counter() - t, 1)\n'
        '    info["comparacion_tensores"] = comparacion\n'
        '    return bool(comparacion["identicos"])\n'
