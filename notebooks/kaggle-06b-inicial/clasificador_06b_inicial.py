        'def hashes_safetensors(rutas: Sequence[str | Path]) -> dict[str, dict]:\n'
        '    """SHA-256 de los bytes de cada tensor (con su dtype y forma), leyendo safetensors sin dependencias."""\n'
        '    res: dict[str, dict] = {}\n'
        '    for ruta in rutas:\n'
        '        with open(ruta, "rb") as f:\n'
        '            cabeza = f.read(8)\n'
        '            if len(cabeza) != 8:\n'
        '                raise AbortoHumo(f"{Path(ruta).name} no es un safetensors válido.")\n'
        '            n = struct.unpack("<Q", cabeza)[0]\n'
        '            if n > 100 * 2**20:\n'
        '                raise AbortoHumo(f"La cabecera de {Path(ruta).name} es demasiado grande.")\n'
        '            cabecera = json.loads(f.read(n))\n'
        '            cabecera.pop("__metadata__", None)\n'
        '            base = 8 + n\n'
        '            for nombre, info in sorted(cabecera.items(), key=lambda kv: kv[1]["data_offsets"][0]):\n'
        '                if nombre in res:\n'
        '                    raise AbortoHumo(f"Tensor repetido entre archivos: {nombre}.")\n'
        '                inicio, fin = info["data_offsets"]\n'
        '                f.seek(base + inicio)\n'
        '                h = hashlib.sha256()\n'
        '                restante = fin - inicio\n'
        '                while restante > 0:\n'
        '                    b = f.read(min(1 << 24, restante))\n'
        '                    if not b:\n'
        '                        raise AbortoHumo(f"{Path(ruta).name} está truncado.")\n'
        '                    h.update(b)\n'
        '                    restante -= len(b)\n'
        '                res[nombre] = {"dtype": info["dtype"], "shape": list(info["shape"]), "sha256": h.hexdigest()}\n'
        '    return res\n'
