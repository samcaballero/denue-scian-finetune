        '    if info.sha != revision:\n'
        '        raise AbortoHumo(f"{repo}: Hugging Face reporta la revisión {info.sha}, no la fijada {revision}.")\n'
        '    verificados = {}\n'
        '    for s in info.siblings:\n'
        '        esperado = _lfs_sha256(s)\n'
        '        local = ruta / s.rfilename\n'
