        'def descargar_verificado(mods, repo: str, revision: str, patrones: Sequence[str] | None = None) -> tuple[Path, dict]:\n'
        '    """Descarga la revisión fijada y verifica la carpeta de la revisión y el SHA-256 de los archivos LFS."""\n'
        '    ruta = Path(mods.hf.snapshot_download(repo_id=repo, revision=revision, allow_patterns=patrones))\n'
