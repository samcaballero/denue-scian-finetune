        'def preparar_tokens(reg: Registro, tok, train: Sequence[Mapping], val: Sequence[Mapping]) -> dict:\n'
        '    """Comprobaciones (a)-(c), etiquetas y filas de más de MAX_SEQ fichas; aborta si algo falla.\n'
        '\n'
        '    (d) (nombres con "<|") se cuenta en la etapa de datos. (b) solo se registra.\n'
        '    """\n'
        '    comp = reg.datos["comprobaciones"]\n'
        '    id_inicio = tok.convert_tokens_to_ids(INICIO_DE_TURNO)\n'
        '    id_fin = tok.convert_tokens_to_ids(FIN_DE_TURNO)\n'
        '    id_fin_texto = tok.convert_tokens_to_ids(TOKEN_FIN_DE_TEXTO)\n'
        '    c_ok = (\n'
        '        tok(INICIO_DE_TURNO, add_special_tokens=False)["input_ids"] == [id_inicio]\n'
        '        and tok(FIN_DE_TURNO, add_special_tokens=False)["input_ids"] == [id_fin]\n'
        '        and tok(TOKEN_FIN_DE_TEXTO, add_special_tokens=False)["input_ids"] == [id_fin_texto]\n'
        '        and len({id_inicio, id_fin, id_fin_texto}) == 3\n'
        '    )\n'
        '    comp["c_tokens_especiales_un_solo_token"] = {\n'
        '        "ok": c_ok, "im_start": id_inicio, "im_end": id_fin, "endoftext": id_fin_texto,\n'
        '    }\n'
        '    if not c_ok:\n'
        '        raise AbortoHumo("(c) <|im_start|>, <|im_end|> o <|endoftext|> no son un solo token.")\n'
        '\n'
        '    filas = [("train", r) for r in train] + [("val", r) for r in val]\n'
        '    # (a) prompt de generación de la plantilla == prompt_generacion, byte a byte.\n'
        '    nombres = [r["nom_estab"] for _, r in filas] + [NOMBRE_INVENTADO]\n'
        '    distintos_a = sum(\n'
        '        tok.apply_chat_template(mensajes(n), tokenize=False, add_generation_prompt=True, enable_thinking=False)\n'
        '        != prompt_generacion(n)\n'
        '        for n in nombres\n'
        '    )\n'
        '    comp["a_prompt_generacion_igual_a_plantilla"] = {"textos": len(nombres), "distintos": distintos_a}\n'
        '    if distintos_a:\n'
        '        raise AbortoHumo(f"(a) La plantilla no da prompt_generacion en {distintos_a} de {len(nombres)} textos.")\n'
        '\n'
        '    # (b) plantilla con la respuesta frente al texto de entrenamiento construido: solo se registra.\n'
        '    cuenta_b = {"igual": 0, "igual_mas_salto_final": 0, "otro": 0}\n'
        '    for _, r in filas:\n'
        '        plantilla = tok.apply_chat_template(\n'
        '            mensajes(r["nom_estab"]) + [{"role": "assistant", "content": r["codigo_act"]}],\n'
        '            tokenize=False, add_generation_prompt=False, enable_thinking=False,\n'
        '        )\n'
        '        texto = texto_entrenamiento(r["nom_estab"], r["codigo_act"])\n'
        '        clave = "igual" if plantilla == texto else ("igual_mas_salto_final" if plantilla == texto + "\\n" else "otro")\n'
        '        cuenta_b[clave] += 1\n'
        '    plantilla_inv = tok.apply_chat_template(\n'
        '        mensajes(NOMBRE_INVENTADO) + [{"role": "assistant", "content": CODIGO_INVENTADO}],\n'
        '        tokenize=False, add_generation_prompt=False, enable_thinking=False,\n'
        '    )\n'
        '    texto_inv = texto_entrenamiento(NOMBRE_INVENTADO, CODIGO_INVENTADO)\n'
        '    if plantilla_inv.startswith(texto_inv):\n'
        '        diferencia = {"plantilla_agrega_al_final": plantilla_inv[len(texto_inv):]}\n'
        '    else:\n'
        '        n = next((i for i, (x, y) in enumerate(zip(plantilla_inv, texto_inv)) if x != y), min(len(plantilla_inv), len(texto_inv)))\n'
        '        diferencia = {"primera_diferencia_en": n, "plantilla": plantilla_inv[n:n + 40], "construido": texto_inv[n:n + 40]}\n'
        '    comp["b_texto_entrenamiento_frente_a_plantilla"] = {\n'
        '        "solo_registro": True, "conteo": cuenta_b, "ejemplo_inventado": diferencia,\n'
        '    }\n'
        '\n'
        '    # Etiquetas y largos.\n'
        '    ejemplos: dict[str, list[dict]] = {"train": [], "val": []}\n'
        '    no_prefijo = etiquetas_mal = 0\n'
        '    largos, etiquetados = [], {}\n'
        '    for conjunto, r in filas:\n'
        '        ids_p = tok(prompt_generacion(r["nom_estab"]), add_special_tokens=False)["input_ids"]\n'
        '        ids_c = tok(texto_entrenamiento(r["nom_estab"], r["codigo_act"]), add_special_tokens=False)["input_ids"]\n'
        '        largos.append(len(ids_c))\n'
        '        try:\n'
        '            etq = etiquetas(ids_p, ids_c)\n'
        '        except ErrorPrompt:\n'
        '            no_prefijo += 1\n'
        '            continue\n'
        '        con_etiqueta = [t for t, e in zip(ids_c, etq) if e != IGNORAR]\n'
        '        etiquetados[len(con_etiqueta)] = etiquetados.get(len(con_etiqueta), 0) + 1\n'
        '        if tok.decode(con_etiqueta, skip_special_tokens=False) != r["codigo_act"] + FIN_DE_TURNO or con_etiqueta[-1] != id_fin:\n'
        '            etiquetas_mal += 1\n'
        '        ejemplos[conjunto].append({"input_ids": ids_c, "labels": etq})\n'
        '    mayores = sum(1 for n in largos if n > MAX_SEQ)\n'
        '    reg.datos["tokens"] = {\n'
        '        "filas": len(filas),\n'
        '        "largo_max": max(largos),\n'
        '        "largo_medio": round(sum(largos) / len(largos), 2),\n'
        '        "mayores_a_max_seq": mayores,\n'
        '        "max_seq_length": MAX_SEQ,\n'
        '        "prompt_no_es_prefijo": no_prefijo,\n'
        '        "etiquetas_distintas_de_codigo_y_fin": etiquetas_mal,\n'
        '        "fichas_etiquetadas_por_fila": {str(k): v for k, v in sorted(etiquetados.items())},\n'
        '    }\n'
        '    if no_prefijo or etiquetas_mal:\n'
        '        raise AbortoHumo(f"Etiquetas: {no_prefijo} filas sin prefijo y {etiquetas_mal} con etiquetas incorrectas.")\n'
        '    if mayores:\n'
        '        raise AbortoHumo(f"{mayores} filas pasan de {MAX_SEQ} fichas; no se trunca.")\n'
        '\n'
        '    # Ejemplo inventado: tabla de etiquetas en el log y en el JSON.\n'
        '    ids_p = tok(prompt_generacion(NOMBRE_INVENTADO), add_special_tokens=False)["input_ids"]\n'
        '    ids_c = tok(texto_inv, add_special_tokens=False)["input_ids"]\n'
        '    etq = etiquetas(ids_p, ids_c)\n'
        '    piezas = [tok.decode([t], skip_special_tokens=False) for t in ids_c]\n'
        '    tabla = tabla_etiquetas(piezas, ids_c, etq)\n'
        '    print("\\n".join(["Tokens del ejemplo inventado (etiqueta -100 = no entra a la pérdida):", *tabla]), flush=True)\n'
        '    con_etiqueta = [p for p, e in zip(piezas, etq) if e != IGNORAR]\n'
        '    print(f"Tokens con etiqueta: {con_etiqueta}", flush=True)\n'
        '    reg.datos["ejemplo_etiquetas"] = {\n'
        '        "codigo": CODIGO_INVENTADO,\n'
        '        "fichas": len(ids_c),\n'
        '        "fichas_con_etiqueta": con_etiqueta,\n'
        '        "tabla": [{"i": i, "id": t, "etiqueta": e, "token": p} for i, (p, t, e) in enumerate(zip(piezas, ids_c, etq))],\n'
        '    }\n'
        '    return {"ejemplos_train": ejemplos["train"], "ids_fin": [id_fin, id_fin_texto]}\n'
